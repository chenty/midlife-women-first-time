#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
骨架生成器（女版 / 男版共用）

用法:
    # 女版（默认）
    python3 scripts/new_article.py "四十岁去考驾照，教练问她是不是家里要买车" --object 座椅 -o draft.md
    # 男版
    python3 scripts/new_article.py "四十三岁去报吉他班，老婆说挺好的别耽误接孩子" --gender m --object 吉他 -o draft.md

生成后填空 → 再用 check_draft.py 质检。
提示: 填不出来的空，就是你还没采到的素材。回去问，别编。
"""

import argparse
from datetime import date
from pathlib import Path

TEMPLATE_F = """# {title}

<!-- 锚点物件：{obj} · 目标 1200–1800 字 · 段落 ≤3 行 · 粗体 ≤5 处 -->

{obj_first}

【某人】在旁边看了半天，问她："【合理的误解 1】？"

她摇头。

"【合理的误解 2】？"

她还是摇头。

这是我在【场景】的第【N】周／次，跟我同车／共事的人，是个【年龄 + 一句性格特征】。我在【我的身份】，见的人多，她给我的印象最深刻。

【旁人的统计式判断】：在【这个地方】，这把年纪【做这件事】的，十个有九个是【大多数人的动机】，但她不是。

【她为什么想要：一件具体往事，含数字】。

**"【她的原话】"**

【反对者的原话 1】；【反对者的原话 2】。

【某人】没硬拦，就是【一句克制的描述】。

这话不算坏，周围不少人都这么想。【把反对方的立场说圆，读者的防备才放下】

我手机上总刷到【别人的宏大故事】，看着都挺远。她没那些，她就是【她做的小事，带量化】。

头一回【做这件事】，她【身体反应】，【失败的画面，带数字】，她自己先笑了。

【关卡】她【失败了几次】。前【N】次都是【具体的失败原因】，第【N+1】次才过。【谁】急了，说她【被嫌弃的话】；【谁】也笑。她不恼，【一个小动作】。

她跟我说，【朴素的自我开解，带"不跟谁比"的意思】。

她算的是另一笔：【把她的账算清楚】
**"【A】都叫【好词】，轮到【B】，才叫【坏词】。"**

这条路也不轻松。【把难堪复述一遍，不加修饰】。到现在【她卡在哪一步】，【结果还没落地】，【学出来到底用不用得上，她自己也不知道】。

我没夸她励志，她也不励志。【具体说明：她并没有因此达成什么了不起的事】。

我只看见她每次【那个动作】，都把{obj}【量化动作】，调到自己的位置，【收束动作】。

【一个画面：她在那里的样子，不慌也不躲】

**{obj}在她手里，【后半句】，她【动词】。**

你心里是不是也有一件【想学、又怕没用】的事？
"""

TEMPLATE_M = """# {title}

<!-- 锚点物件：{obj} · 目标 1200–1800 字 · 段落 ≤3 行 · 粗体 ≤5 处 · 男版：不许自怜 -->

{obj_first}

我问他这是怎么了。他说不是怎么了，是【一个具体的困难】。

这是我【场景】的人，【年龄】，【一句性格特征】，话不多。我在【我的身份】，见的人多，他给我的印象最深刻。

【旁人的统计式判断】：在这条街上，四十多岁的人闲下来都【大多数人的选择】，他不是。

今年【几月】他【做的小事，带花费和数字】。他跟我说的时候，我顺口问了一句，【谁】同意吗？

他说，她说挺好的，【一句体贴的附加条件，比如"别耽误接孩子"】。

我后来又问了两个人。【某人】说，【一句轻】。【某人】说，【一句轻】。

没有一个人说不行。

也没有一个人接着往下问。

他说，怪就怪在这儿。要是有人拦我，我倒好办了。

**"【他的原话】"**

【他为什么想要：一件具体往事，含数字】。

我手机上总刷到【别人的宏大故事】，看着都挺远。他没那些，他就是【他做的小事，带量化】。

头一回【做这件事】，他【身体反应】，【失败的画面，带数字】。

【关卡／课程】他去了【N】次。【在场最小／最有资格的那个人】管他叫【称呼】。他不恼，【一个小动作】。

他跟我说这些的时候，不像在抱怨，倒像在报账。
**"【A】都叫【好词】，轮到【B】，才叫【坏词】。"**

到现在【他卡在哪一步】，【结果还没落地】，【做成了到底用不用得上，他自己也不知道】。

我也没夸他。他不需要谁夸。

我只看见他每次【那个动作】，都把{obj}【量化动作】，【收束动作】。

【一个画面：窗口／柜台／灯下，他在其中，没抬头】

**{obj}搁在【哪儿】，【后半句】，他【动词】。**

你要做的那件事，有人反对过吗？
"""

OBJ_HINT_F = {
    "座椅": "上车第一件事，她把驾驶座往前调，调一下，坐一坐，再调一下。",
    "方向盘": "上车第一件事，她把手放到方向盘上，握一下，松一下，再握紧。",
    "钥匙": "出门前，她把钥匙在手里翻了两下，才插进去。",
}

OBJ_HINT_M = {
    "吉他": "他把吉他搁在腿上，左手摁第三根弦，摁一下，松手，再摁一下。",
    "跑鞋": "鞋柜最下面那双跑鞋，他拿出来，放回去，又拿出来。",
    "工牌": "下班进门，他先把工牌从脖子上摘下来，搁在鞋柜上。",
    "相机": "他把相机从包里拿出来，打开盖子，又扣上。",
    "钥匙": "出门前，他把钥匙在手里翻了两下，才插进去。",
}


def main():
    ap = argparse.ArgumentParser(
        description="生成《中年女人的第一次》/《中年男人的第一次》骨架草稿")
    ap.add_argument("title", nargs="?",
                    default="【标题：年龄+身份 + 小事 + 一句外部的话】")
    ap.add_argument("--object", "-o", dest="obj", default="【锚点物件】",
                    help="锚点物件，如 座椅 / 方向盘 / 吉他 / 跑鞋")
    ap.add_argument("--gender", "-g", choices=["f", "m"], default="f",
                    help="f=女版（默认），m=男版")
    ap.add_argument("--out", "-f", default="draft.md", help="输出文件")
    a = ap.parse_args()

    obj = a.obj
    if a.gender == "m":
        tmpl, hints = TEMPLATE_M, OBJ_HINT_M
        first = hints.get(obj, f"他把{obj}拿出来，【动作三拍：动一下，停一下，再动一下】。")
    else:
        tmpl, hints = TEMPLATE_F, OBJ_HINT_F
        first = hints.get(obj, f"上车第一件事，她把{obj}【动作三拍：动一下，停一下，再动一下】。")

    text = tmpl.format(title=a.title, obj=obj, obj_first=first)
    out = Path(a.out)
    if out.exists():
        print(f"⚠️  目标文件已存在，未覆盖：{out}\n   换个 --out 或先备份。")
        return 1
    out.write_text(text, encoding="utf-8")

    print(f"✅ 骨架已生成：{out}")
    print(f"   标题：{a.title}")
    print(f"   物件：{obj}   版本：{'男版' if a.gender == 'm' else '女版'}")
    print(f"   今天：{date.today().isoformat()}")
    print("\n下一步：")
    print("  1. 把【】填掉。填不出来的空 = 还没采到的素材，回去问，别编。")
    print(f"  2. 填完跑：python3 scripts/check_draft.py {out} --object {obj}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
